def _bibtex_record(rec: Dict[str, str]) -> str:
    """Render a single BibTeX entry."""
    bibtype = rec.get("type") or "misc"
    key = rec.get("key") or "anon"
    body_keys = [k for k in rec.keys() if k not in ("type", "key")]
    lines = [f"@{bibtype}{{{key},"]
    for k in body_keys:
        v = rec[k]
        if v is None:
            continue
        lines.append(f"  {k} = {{{v}}},")
    # Remove trailing comma from last line for cleanliness.
    if lines[-1].endswith(","):
        lines[-1] = lines[-1][:-1]
    lines.append("}")
    return "\n".join(lines)


def generate_references_bib(bundle: Dict[str, Any]) -> str:
    """Build a BibTeX file from the bundle's method_registry + any
    inline ``seed:*`` citations in findings.

    Unknown methods get a placeholder ``@misc{aurora-<slug>, ...}``
    entry the author can fill in.
    """
    used: List[Dict[str, str]] = []
    seen_keys: set = set()

    # 1. Citations for every method that appeared in findings.
    #    Combined tags (e.g., "ISO-FOREST + ROBUST-Z") yield multiple
    #    citations — see _match_methods.
    registry = bundle.get("method_registry") or {}
    for method_name in registry.keys():
        matches = _match_methods(method_name)
        if matches:
            for key in matches:
                rec = _BUILTIN_CITATIONS[key]
                if rec["key"] not in seen_keys:
                    used.append(rec)
                    seen_keys.add(rec["key"])
        else:
            slug = "".join(
                c if c.isalnum() else "-" for c in str(method_name).lower()
            ).strip("-")[:48] or "anon"
            placeholder_key = f"aurora-{slug}"
            if placeholder_key not in seen_keys:
                used.append({
                    "key": placeholder_key,
                    "type": "misc",
                    "author": "Aurora-QIE (method tag, fill in)",
                    "title": str(method_name),
                    "year": str(datetime.now(timezone.utc).year),
                    "note": "Method tag emitted by Aurora; fill in canonical citation.",
                })
                seen_keys.add(placeholder_key)

    # 2. Aurora itself.
    aurora_v = bundle.get("aurora_version") or "unknown"
    if "aurora-qie" not in seen_keys:
        used.append({
            "key": "aurora-qie",
            "type": "software",
            "title": "Aurora-QIE: Quantitative Intelligence Console",
            "author": "Aurora-QIE Contributors",
            "version": aurora_v,
            "year": str(datetime.now(timezone.utc).year),
            "url": "https://aurora-qie.dev",
            "note": "Local-first glass-box quantitative analysis tool.",
        })
        seen_keys.add("aurora-qie")

    return "\n\n".join(_bibtex_record(r) for r in used) + "\n"


def generate_methods_md(bundle: Dict[str, Any]) -> str:
    """Produce a journal-ready Methods.md section.

    Structure:
      # Methods
      ## Data
      ## Pipeline overview
      ## Methods used
        ### <Method 1>
        ...
      ## Assumptions
      ## Confidence
      ## Reproducibility
    """
    ds = bundle.get("dataset") or {}
    struct = bundle.get("structure") or {}
    sm = bundle.get("system_model") or {}
    aurora_v = bundle.get("aurora_version") or "unknown"
    run = bundle.get("run") or {}
    integ = bundle.get("integrity") or {}
    assumptions = bundle.get("assumptions") or []
    registry = bundle.get("method_registry") or {}

    def _esc(s: Any) -> str:
        return str(s).replace("_", "\\_") if s is not None else "—"

    lines: List[str] = []
    lines.append("# Methods\n")
    lines.append(
        f"_All analyses were performed with Aurora-QIE v{aurora_v} "
        f"(bundle hash: `{integ.get('content_hash', 'n/a')}`). All "
        f"thresholds and citations below reflect Aurora's "
        f"glass-box defaults; no findings were generated by an LLM._\n"
    )

    # Data
    lines.append("## Data\n")
    lines.append(
        f"The input dataset (`{_esc(ds.get('basename') or ds.get('name'))}`) "
        f"contains {ds.get('rows', '?')} rows and {ds.get('cols', '?')} "
        f"columns "
        f"({'with' if struct.get('time_axis') else 'without'} a regular "
        f"time axis"
        + (f", cadence {_esc(struct.get('cadence'))}" if struct.get('time_axis') else "")
        + ").\n"
    )
    if ds.get("sha256"):
        lines.append(
            f"The dataset SHA-256 hash is `{ds['sha256']}`. "
            "Including this in your supplementary material allows "
            "readers to verify the exact file analysed.\n"
        )

    # Pipeline overview
    lines.append("## Pipeline overview\n")
    tier = run.get("tier") or "auto"
    lines.append(
        f"Aurora was run at depth `{tier}`, which executes tier-1 "
        f"(anomaly + regime + motif + AR baseline forecast) followed by "
        f"tier-2 (Bayesian, Granger, Gaussian process, wavelet, "
        f"topology) and, when `full`, tier-3 (full-data replication). "
        f"Every finding is tagged with the method that produced it, "
        f"the threshold applied, and a citation; findings without "
        f"complete provenance are flagged `fabricated`.\n"
    )

    # Methods used
    lines.append("## Methods used\n")
    if not registry:
        lines.append("_No method-tagged findings in this run._\n")
    for method_name, rec in registry.items():
        count = rec.get("count", 0)
        sevs = rec.get("severities") or {}
        sev_str = ", ".join(f"{k}={v}" for k, v in sevs.items()) or "—"
        normal = _normalise_method(method_name)
        cite = _BUILTIN_CITATIONS.get(normal)
        cite_inline = f" [{cite['key']}]" if cite else ""
        lines.append(f"### {method_name}{cite_inline}\n")
        lines.append(
            f"- Findings produced: {count} ({sev_str})\n"
        )
        desc = _METHOD_DESCRIPTIONS.get(normal)
        if desc:
            lines.append(desc + "\n")
        else:
            lines.append(
                "_Plain-English description not yet curated for this "
                "method tag — fill in for camera-ready._\n"
            )

    # Assumptions
    lines.append("## Assumptions\n")
    if assumptions:
        for a in assumptions:
            lines.append(f"- {a}\n")
    else:
        lines.append("_No assumptions explicitly declared in this run._\n")

    # Confidence
    conf = sm.get("confidence")
    lines.append("## Confidence\n")
    if conf is not None:
        pct = round(float(conf) * 100)
        tier_label = ("strong (template anchored)" if pct >= 60
                      else "moderate (partial anchoring)" if pct >= 30
                      else "low (mostly inferred)")
        lines.append(
            f"The overall system-model confidence is **{pct}%** "
            f"({tier_label}). Confidence reflects the slot-fill rate of "
            f"the matched domain template multiplied by the strength of "
            f"the discovered relationships and the satisfaction of "
            f"declared constraints.\n"
        )
    else:
        lines.append("_System-model confidence not available._\n")

    # Reproducibility
    lines.append("## Reproducibility\n")
    lines.append(
        f"All analyses are reproducible from the accompanying "
        f"`replication.json` and the source dataset. Re-running "
        f"Aurora-QIE v{aurora_v} on the same file should yield a "
        f"bundle whose content hash matches "
        f"`{integ.get('content_hash', 'n/a')}` exactly. Floating-point "
        f"non-determinism in some advanced methods (e.g., Gaussian "
        f"process MCMC sampling, when enabled) may produce numerically "
        f"close but not bit-identical results; tier-1 statistics are "
        f"fully deterministic.\n"
    )

    return "".join(lines)


def generate_replication_json(bundle: Dict[str, Any]) -> Dict[str, Any]:
    """Deterministic re-run config.

    Captures every input a third party needs to reproduce this run.
    """
    ds = bundle.get("dataset") or {}
    run = bundle.get("run") or {}
    integ = bundle.get("integrity") or {}
    return {
        "schema": "aurora.replication/v1",
        "aurora_version": bundle.get("aurora_version"),
        "bundle_hash": integ.get("content_hash"),
        "dataset": {
            "basename": ds.get("basename"),
            "sha256": ds.get("sha256"),
            "rows": ds.get("rows"),
            "cols": ds.get("cols"),
            "size_mb": ds.get("size_mb"),
        },
        "run": {
            "id": run.get("run_id"),
            "tier": run.get("tier") or "auto",
            "started_at": run.get("started_at"),
            "completed_at": run.get("completed_at"),
        },
        "instructions": [
            "1. Install Aurora-QIE at the version listed above.",
            "2. Obtain the dataset file matching the listed SHA-256.",
            "3. Run: `aurora analyze <dataset> --depth <tier>`",
            "4. Verify the new bundle's content_hash matches bundle_hash above.",
            "   Bit-identical for tier-1; numerically close for tier-2/3 advanced methods.",
        ],
    }


def generate_zenodo_json(bundle: Dict[str, Any],
                         *,
                         title: Optional[str] = None,
                         creators: Optional[List[Dict[str, str]]] = None,
                         keywords: Optional[List[str]] = None,
                         description: Optional[str] = None,
                         ) -> Dict[str, Any]:
    """Zenodo deposit metadata. Mint a DOI by uploading the kit directory
    to Zenodo with this file at the root.

    See https://developers.zenodo.org/#representation for the schema.
    """
    run = bundle.get("run") or {}
    ds = bundle.get("dataset") or {}
    sm = bundle.get("system_model") or {}
    integ = bundle.get("integrity") or {}

    default_title = (
        title or
        f"Aurora-QIE analysis of {ds.get('basename') or 'dataset'} "
        f"(run {run.get('run_id') or 'unknown'})"
    )
    default_desc = (description or
        "Aurora-QIE quantitative analysis bundle, including findings, "
        "methods, assumptions, and a cryptographically-hashed "
        "reproducibility manifest. The accompanying methods.md is "
        "publication-ready; references.bib lists every cited prior. "
        "Aurora-QIE bundle hash: " + str(integ.get("content_hash") or "n/a")
    )
    return {
        "metadata": {
            "title": default_title,
            "description": default_desc,
            "creators": creators or [{"name": "Aurora-QIE User"}],
            "keywords": keywords or [
                "Aurora-QIE",
                "quantitative analysis",
                "anomaly detection",
                "reproducible research",
                "glass-box AI",
            ],
            "upload_type": "dataset",
            "publication_date": (run.get("completed_at") or "").split("T")[0]
                                  or datetime.now(timezone.utc).strftime("%Y-%m-%d"),
            "access_right": "open",
            "license": "CC-BY-4.0",
            "notes": (
                f"Generated by aurora_sdk research_kit. Aurora-QIE v"
                f"{bundle.get('aurora_version') or 'unknown'}. "
                f"Findings produced: "
                f"{sum((r.get('count', 0) for r in (bundle.get('method_registry') or {}).values()), 0)}. "
                f"Confidence: {round((sm.get('confidence') or 0) * 100)}%."
            ),
            "related_identifiers": [
                {
                    "scheme": "url",
                    "identifier": "https://aurora-qie.dev",
                    "relation": "isDerivedFrom",
                    "resource_type": "software",
                },
            ],
        }
    }


