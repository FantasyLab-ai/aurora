def _normalise_method(name: str) -> str:
    """Lowercase + strip + simplify a method tag to its citation key.

    Returns the FIRST matched citation key (used by methods.md for the
    inline ``[key]`` tag). For full citation emission (in the bib
    file), use ``_match_methods`` which returns every match.
    """
    n = str(name or "").lower().strip()
    for k in _BUILTIN_CITATIONS:
        if k in n:
            return k
    return n


def _match_methods(name: str) -> List[str]:
    """Return EVERY citation key that appears in the given method tag.

    Combined tags like "ISO-FOREST + ROBUST-Z" deserve both citations
    in references.bib; this is the multi-match resolver that supports
    that. Order preserves _BUILTIN_CITATIONS insertion order.
    """
    n = str(name or "").lower().strip()
    return [k for k in _BUILTIN_CITATIONS if k in n]


