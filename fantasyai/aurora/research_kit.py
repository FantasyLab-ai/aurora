"""
Aurora Research Kit — publication-ready output from an Aurora Bundle.

Generates a directory tree suitable for academic publication:

    research_kit/
      README.md             — orientation: what's in here, how to cite
      methods.md            — full methods section (LaTeX-ready Markdown)
      references.bib        — BibTeX of every prior + every reference
      replication.json      — deterministic re-run config + hashes
      .zenodo.json          — Zenodo deposit metadata (DOI-mintable)
      bundle.aurora.json    — the source bundle this kit was built from

This module is purely additive: it reads an Aurora Bundle (the
``aurora_sdk.Bundle`` artifact built in Phase 1) and writes files. No
network calls, no environment dependencies beyond stdlib.

Design notes:

  * Methods.md is structured around the ``method_registry`` block in
    the bundle, with one subsection per distinct method used. Each
    subsection lists the threshold, the citation, and a one-paragraph
    plain-English description. The bundle's ``assumptions`` list is
    surfaced as a top-level "Assumptions" section.

  * references.bib is generated by transforming the bundle's
    ``method_registry`` keys + any explicit ``seed:*`` citations
    found in findings into BibTeX records. We use a small built-in
    library of canonical citations (Hampel 1974 for robust z-score,
    Liu 2008 for isolation forest, etc.); unknown methods get a
    placeholder ``@misc`` entry the author can fill in.

  * replication.json captures: aurora_version, bundle_hash, dataset
    sha256 (when known), tier, seed, output_root. Anyone with Aurora
    installed and the original dataset can re-run and verify.

  * .zenodo.json is the Zenodo-compatible metadata file. Mint a DOI
    by uploading the research_kit directory to Zenodo.

Security: no shell, no network, no eval. Output is restricted to a
caller-provided directory.
"""
